"""
eval_mentions.py — ตัวตรวจกลางของเครื่องมือวัดผล: ชื่อรุ่น/ชื่องานในคำตอบ "ถูกแนะนำ" หรือ "ถูกตัดออก"

ใช้โดย simulate_customers.score (ผิดเงื่อนไข) และ run_answer_eval (must_not_contain แบบ forbid_anywhere)
ไม่ใช่โค้ดของบอท — เปลี่ยนแค่วิธีให้คะแนน ไม่เปลี่ยนคำตอบที่ลูกค้าเห็น

ปัญหาเดิม (ผู้ใช้สั่งแก้ 26 ต.ค.)
    ตัวตรวจดูแค่ว่า "มีชื่อในข้อความไหม" แยกไม่ออกระหว่าง
        "แนะนำ SM254 FG50% ครับ"                         ← ผิดจริง
        "SM254 FG50% ทนแห้งได้แค่ 116 °C จึงไม่ถึง 120 °C" ← บอทเตือนถูกต้อง
    sim4 G02 (ทั้งสองรอบ) · graph_apps GA-F03 (r1 · r2) ตกเพราะแบบหลัง

กฎ (ทีละบรรทัด — คำตอบของบอทเขียนเป็นรายการ แต่ละบรรทัดพูดถึงรุ่น/งานเดียว)
    บรรทัดที่มีคำบอกว่าตัดออก (ไม่ถึง · ไม่ผ่าน · ไม่มีเกรด · ใช้ไม่ได้ …) = ตัดออก ไม่นับ
    "ไม่แนะนำให้ใช้ในสภาวะเปียก" เป็นคุณสมบัติของเกรด ไม่ใช่การตัดออก — ลบออกก่อนตรวจ
    ทั้งเทิร์นบอกว่า "ไม่มีรุ่นที่ตรง…" → ชื่อรุ่นในเทิร์นนั้นเป็นคำอธิบาย ยกเว้นบรรทัดที่มีคำว่าแนะนำ
    บรรทัดข้อความส่งต่อฝ่ายขาย (โค้ดต่อท้าย) ไม่ใช่การแนะนำ
"""
from __future__ import annotations

import re

# "ไม่แนะนำให้ใช้(เกรดนี้)ในสภาวะเปียก" = คุณสมบัติของเกรด (sim2 G09 · SM254 FG50%)
WET_NOTE_RX = re.compile(r"ไม่แนะนำ[^\n,()]{0,30}?เปียก")
# "ไม่มีเกรด PP สำหรับรุ่นนี้" = หมายเหตุเกรดของรุ่นที่ยังแนะนำอยู่ (sim2 G01 HC127 C · G06 EC508 PR11)
# ใช้เฉพาะตอนตรวจชื่อรุ่น — ตอนตรวจชื่องาน "ไม่มีเกรด…" แปลว่ารุ่นนี้ใช้กับงานนั้นไม่ได้ (GA-F03)
# "ไม่มีเกรดใดของรุ่นนี้ที่รองรับ…" = ตัดทั้งรุ่น (sim4 G02#2) — ไม่ใช่หมายเหตุเกรด จึงไม่ลบ
# "เกรด PP ไม่ผ่านช่วงอุณหภูมิ -30 °C" = เกรดเดียวไม่ผ่าน รุ่นยังแนะนำด้วยเกรดอื่น (sim3 G04 EC508 C)
GRADE_NOTE_RX = re.compile(r"(?:ไม่มี(?:ระบุ)?|ไม่ได้ระบุ)เกรด\s*[A-Z][A-Z0-9]*(?:\s*[,/และ]+\s*[A-Z][A-Z0-9]*)*"
                           r"|เกรด\s*[A-Z][A-Z0-9]*(?:/[A-Z][A-Z0-9]*)?\s*(?:ไม่ผ่าน|ไม่ถึง|ไม่รองรับ)")
EXCLUDE_RX = re.compile(
    r"ไม่ถึง|ไม่ผ่าน|ใช้ไม่ได้|ใช้งานไม่ได้|ไม่รองรับ|ไม่ครอบคลุม|ไม่มี(?:ระบุ)?เกรด|ไม่ได้ระบุเกรด|ไม่ได้ผลิต|ไม่ตรง|"
    r"ตัดออก|ถูกตัด|คัดออก|ติดเงื่อนไข|ไม่สามารถ|ไม่แนะนำ|ไม่เหมาะ|ไม่ใช่ตัวเลือก|พิทช์\S{0,6}ไม่ใช่|ไม่ใช่\s*\d|"
    r"ต้องสอบถามฝ่ายขายโดยตรง")
RECOMMEND_RX = re.compile(r"(?<!ไม่)แนะนำ|ตัวเลือกตรงรุ่น")
NONE_RX = re.compile(r"ไม่มีรุ่นที่|ไม่มีสายพาน.*ที่ตรง|ไม่พบรุ่น|ไม่มีรุ่นใด|ไม่มีรุ่นไหน")


_ITEM_RX = re.compile(r"^(\s*)(?:[-*•]|\d+[.)])\s")


def _lines(text: str) -> list[str]:
    """บรรทัด · รายการที่มีรายการย่อยเยื้องเข้าไป รวมเป็นก้อนเดียว
    sim5 G02: "1. **รุ่น SM254 FG50%** (พิทช์ตรงตามที่ต้องการ):" แล้วบรรทัดย่อย "* … 116 °C ซึ่งยังไม่ถึง 120 °C"
    คำว่าไม่ถึงอยู่บรรทัดย่อย ดูทีละบรรทัดจึงนับเป็นแนะนำ"""
    out: list[list] = []                   # [ข้อความ, ระดับเยื้องของหัวรายการ]
    for l in (text or "").split("\n"):
        if not l.strip():
            continue
        m = _ITEM_RX.match(l)
        indent = len(l) - len(l.lstrip())
        if out and out[-1][1] is not None and indent > out[-1][1] and (m or l.startswith(" ")):
            out[-1][0] += " " + l.strip()  # รายการย่อย/บรรทัดต่อของรายการก่อนหน้า
            continue
        out.append([l, indent if m else None])
    return [t for t, _ in out]


def line_excludes(line: str, grade_note_excludes: bool = True) -> bool:
    """บรรทัดนี้พูดถึงสิ่งที่ถูกตัดออก/ใช้ไม่ได้"""
    s = WET_NOTE_RX.sub(" ", line or "")
    if not grade_note_excludes:
        s = GRADE_NOTE_RX.sub(" ", s)
    return bool(EXCLUDE_RX.search(s))


def recommended(term: str, text: str, contains=None, grade_note_excludes: bool = True) -> bool:
    """term ถูกเอ่ยถึงแบบแนะนำ/ยืนยันในข้อความนี้อย่างน้อยหนึ่งบรรทัด
    contains(term, line) — วิธีหาว่าบรรทัดมี term ไหม (ค่าเริ่มต้น: substring ไม่สนตัวพิมพ์)"""
    has = contains or (lambda t, l: t.lower() in l.lower())
    none_turn = bool(NONE_RX.search(text or ""))
    for line in _lines(text):
        if not has(term, line):
            continue
        if line_excludes(line, grade_note_excludes):
            continue
        if none_turn and not RECOMMEND_RX.search(WET_NOTE_RX.sub(" ", line)):
            continue                                     # "ไม่มีรุ่นที่ตรง…" → ชื่อรุ่นเป็นคำอธิบาย
        return True
    return False
