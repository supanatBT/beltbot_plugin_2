import eval_mentions as EM  # noqa: E402

passed = failed = 0


def ok(name, cond, detail=""):
    global passed, failed
    if cond:
        passed += 1
        print(f"  ✓ {name}")
    else:
        failed += 1
        print(f"  ✗ {name}  {detail}")


def rec(code, text, grade_note_excludes=False):
    return EM.recommended(code, text, grade_note_excludes=grade_note_excludes)


