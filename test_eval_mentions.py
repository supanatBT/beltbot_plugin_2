    ("HC127 C", "4. **HC127 C** — เกรดวัสดุ **POM** (พิทช์ 12.7 มม.) *(หมายเหตุ: แคตตาล็อก 2026 ไม่มีเกรด PP สำหรับรุ่นนี้)*"),
